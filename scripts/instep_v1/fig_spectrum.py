#!/usr/bin/env python3
"""InStep paper appendix: how many leading principal directions of each verifier's state the
correctness signal needs (signal_anatomy.py's spectrum). pgfplots body for the InStep repo.

Reads signal_anatomy.py results, as its JSON or its log lines ("[anatomy] <key> budget ... |
spectrum 1:0.754 2:0.846 ... all:0.852 | reliance ..."), later sources overriding earlier ones per
key, and writes one axis: mean test AUROC over the eight sets of the probe fitted on the top k
principal directions, k = 1, 2, 4, ..., 256, with the all-dimension probe at the right end.

    python scripts/instep_v1/fig_spectrum.py --src results/instep_v1/signal/signal_anatomy_*.log \\
        results/instep_v1/signal/signal_anatomy_sep.json --out ~/Code/InStep/figures/plots/signal_spectrum.tex
"""

from __future__ import annotations

import argparse
import json
import re
from pathlib import Path

# key -> (label, colour, line width), drawing order: references first, InStep on top
STYLE = {"passive_final": ("text token", "neutraldark", 1.0), "prm_final": ("PRM separator", "prmcol", 1.0),
         "reprobe_rep": ("ReProbe", "rpcol", 1.0), "sep": ("step token", "instepdark", 1.6)}
X_ALL = 1024  # where the all-dimension probe is drawn (log axis; the largest k is 256)
LINE = re.compile(r"\[anatomy\]\s+(\S+).*?\| spectrum (.*?) \|")


def load(paths: list[Path]) -> dict[str, dict[str, float]]:
    """{key: {k: AUROC}} from anatomy JSON files and logs, later files winning per key."""
    out: dict[str, dict[str, float]] = {}
    for p in paths:
        text = p.read_text()
        if p.suffix == ".json":
            for r in json.loads(text)["keys"]:
                out[r["key"]] = {k: float(v) for k, v in r["spectrum_auroc"].items()}
            continue
        for m in LINE.finditer(text):
            out[m.group(1)] = {k: float(v) for k, v in (kv.split(":") for kv in m.group(2).split())}
    return out


def figure(spec: dict[str, dict[str, float]]) -> str:
    L = ["% generated by scripts/instep_v1/fig_spectrum.py",
         "\\begin{tikzpicture}",
         "\\begin{axis}[width=\\linewidth, height=4.2cm, xmode=log, log basis x=2, xmin=0.8, xmax=1300,",
         "  ymin=0.45, ymax=0.88, xtick={1,4,16,64,256,1024}, xticklabels={1,4,16,64,256,all},",
         "  xlabel={Leading principal directions}, ylabel={Test AUROC},",
         "  tick label style={font=\\footnotesize}, label style={font=\\small},",
         "  yticklabel style={/pgf/number format/fixed, /pgf/number format/precision=2}]"]
    for key, (label, col, lw) in STYLE.items():
        if key not in spec:
            continue
        pts = sorted((X_ALL if k == "all" else int(k), v) for k, v in spec[key].items())
        L.append(f"\\addplot[{col}, mark=none, line width={lw}pt] coordinates {{"
                 + " ".join(f"({x},{v:.3f})" for x, v in pts) + "};")
    ys = {"sep": 0.36, "reprobe_rep": 0.27, "prm_final": 0.18, "passive_final": 0.09}
    for key, (label, col, _) in STYLE.items():
        if key in spec:
            L.append(f"\\node[font=\\scriptsize, text={col}, anchor=east, inner sep=1pt] "
                     f"at (rel axis cs:0.97,{ys[key]}) {{{label}}};")
    L += ["\\end{axis}", "\\end{tikzpicture}"]
    return "\n".join(L) + "\n"


def main() -> None:
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--src", type=Path, nargs="+", required=True)
    p.add_argument("--out", type=Path, required=True)
    a = p.parse_args()
    spec = load(a.src)
    a.out.parent.mkdir(parents=True, exist_ok=True)
    a.out.write_text(figure(spec))
    print(a.out, sorted(spec))


if __name__ == "__main__":
    main()
