#!/usr/bin/env python3
"""InStep paper, "what the offsets do": the step token's state with and without per-layer offsets,
on its two leading principal directions (pgfplots body for the InStep repo).

Reads offset_view.py outputs: <view>/<token>.csv (test steps: every incorrect one and 600 sampled
correct ones per set; spc1, spc2 = projections on the top two principal directions of the
token's per-dimension standardized validation states, fitted without labels) and
<view>/summary.json. One panel per --panels token; each draws --per_class steps of each class
(pooled over the 8 test sets, equal counts so neither class hides the other), correct steps grey
and incorrect ones in errcol. Principal directions have no sign: each axis is flipped so that the
incorrect steps' mean is positive (orientation only). Axes are clipped to the central 99.5%.

    python scripts/instep_v1/fig_offset_view.py --view results/instep_v1/offset_view \\
        --out ~/Code/InStep/figures/plots/offset_view.tex
"""

from __future__ import annotations

import argparse
import csv
import json
from pathlib import Path

import numpy as np

TITLES = {"emb": "Embedding only", "off": "+ offsets", "instep": "InStep"}


def load(path: Path, a: str = "spc1", b: str = "spc2") -> tuple[np.ndarray, np.ndarray]:
    rows = list(csv.DictReader(open(path)))
    y = np.array([int(r["y"]) for r in rows])
    X = np.array([[float(r[a]), float(r[b])] for r in rows])
    return X, y


def orient(X: np.ndarray, y: np.ndarray) -> np.ndarray:
    return X * np.where(X[y == 1].mean(0) >= 0, 1.0, -1.0)


def sample(y: np.ndarray, per_class: int, seed: int = 0) -> np.ndarray:
    rng = np.random.default_rng(seed)
    idx = [rng.choice(np.flatnonzero(y == c), min(per_class, int((y == c).sum())), replace=False) for c in (0, 1)]
    return np.concatenate(idx)


def panel(X: np.ndarray, y: np.ndarray, title: str, note: str, per_class: int, first: bool) -> str:
    X = orient(X, y)
    Z = (X - X.mean(0)) / X.std(0)  # each axis in its own standard deviations
    lo, hi = np.percentile(Z, 0.25, axis=0), np.percentile(Z, 99.75, axis=0)
    keep = sample(y, per_class)
    L = ["\\begin{tikzpicture}",
         "\\begin{axis}[width=0.54\\linewidth, height=4.4cm, xtick=\\empty, ytick=\\empty,",
         f"  xmin={lo[0]:.2f}, xmax={hi[0]:.2f}, ymin={lo[1]:.2f}, ymax={hi[1]:.2f},",
         f"  title={{{title} ({note})}}, title style={{font=\\small, yshift=-4pt}}, label style={{font=\\small}},",
         "  xlabel={PC 1}" + (", ylabel={PC 2}" if first else "") + "]"]
    for c, style in ((0, "black!35, opacity=0.45"), (1, "errcol, opacity=0.45")):
        sel = [i for i in keep if y[i] == c]
        pts = " ".join(f"({Z[i, 0]:.2f},{Z[i, 1]:.2f})" for i in sel
                       if lo[0] <= Z[i, 0] <= hi[0] and lo[1] <= Z[i, 1] <= hi[1])
        L.append(f"\\addplot[only marks, mark=*, mark size=0.3pt, {style}] coordinates {{{pts}}};")
    L += ["\\end{axis}", "\\end{tikzpicture}"]
    return "\n".join(L)


def figure(view: Path, panels: list[str], per_class: int) -> str:
    S = json.loads((view / "summary.json").read_text())
    out = ["% generated by scripts/instep_v1/fig_offset_view.py"]
    for j, t in enumerate(panels):
        X, y = load(view / f"{t}.csv")
        note = f"{S[t]['logit']['mean_ap']:.3f}"  # the token's own test PR-AUC, 8-set mean
        out.append(panel(X, y, TITLES.get(t, t), note, per_class, j == 0) + ("\\hfill" if j < len(panels) - 1 else ""))
    return "\n".join(out) + "\n"


def main() -> None:
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--view", type=Path, required=True)
    p.add_argument("--panels", default="emb,off")
    p.add_argument("--per_class", type=int, default=1500)
    p.add_argument("--out", type=Path, required=True)
    a = p.parse_args()
    a.out.parent.mkdir(parents=True, exist_ok=True)
    a.out.write_text(figure(a.view, a.panels.split(","), a.per_class))
    print(a.out)


if __name__ == "__main__":
    main()
