#!/usr/bin/env python3
"""InStep paper, "where the signal lives": pgfplots bodies from signal_geometry.py outputs.

  signal_depth.tex  (a) test PR-AUC of the same linear probe against relative depth, for
                    Qwen3-8B's text state at the step's last token, InStep's step token and
                    Qwen2.5-Math-PRM-7B's separator; ReProbe's pooled step representation as
                    one point at the top. (b) test AUROC of the raw class-mean axis (no learned
                    metric) on the same states.
  signal_view.tex   held-out 2D view of each method's final representation (x: the probe's
                    logit, y: the first principal direction orthogonal to the probe), incorrect
                    steps in the method's colour over correct ones in grey; at most --per_class
                    steps per class and set, x and y standardized per panel.

Colours follow the paper (main.tex): instepdark, rpcol, prmcol; the text state is black!55.

    python scripts/instep_v1/fig_signal.py --signal results/instep_v1/signal --out ~/Code/InStep/figures/plots
"""

from __future__ import annotations

import argparse
import csv
import json
from pathlib import Path

import numpy as np

LINES = [  # family, colour, width, label
    ("text", "black!55", "0.8pt", "text token"),
    ("prm", "prmcol", "0.8pt", "PRM separator"),
    ("instep", "instepdark", "1.2pt", "step token"),
]
PANELS = [  # final key, title, colour
    ("passive_final", "Text token", "black!70"),
    ("reprobe_rep", "ReProbe", "rpcol"),
    ("prm_final", "Qwen2.5-Math-PRM-7B", "prmcol"),
    ("sep", "InStep", "instepdark"),
]
HEAD = ("width={w}, height={h}, tick label style={{font=\\footnotesize}}, label style={{font=\\small}}, "
        "title style={{font=\\small, yshift=-4pt}}")


def curve(keys: list[dict], fam: str, field: str) -> list[tuple[float, float]]:
    pts = []
    for k in keys:
        # the curves use block outputs; the post-norm final states of the text and the step
        # token sit at depth 1 next to block 35 (the PRM's states stop at block 23, so its
        # final state is its last point)
        if k["family"] != fam or k["key"] in ("passive_final", "sep"):
            continue
        v = k[field]["all"] if isinstance(k[field], dict) else k[field]
        pts.append((100 * k["depth"], v))
    return sorted(pts)


def coords(pts) -> str:
    return " ".join(f"({x:.1f},{y:.3f})" for x, y in pts)


def depth_axis(keys: list[dict], field: str, ylabel: str, ymin: float, ymax: float, w: str, labels: bool) -> str:
    L = ["\\begin{tikzpicture}", "\\begin{axis}[" + HEAD.format(w=w, h="3.6cm") + ",",
         f"  ymajorgrids, grid style={{gray!20}}, xmin=0, xmax=100, ymin={ymin}, ymax={ymax},",
         "  xtick={0,25,50,75,100}, xlabel={Depth (\\% of layers)}, "
         f"ylabel={{{ylabel}}}, yticklabel style={{/pgf/number format/fixed, /pgf/number format/precision=2}}]"]
    for fam, col, wd, lab in LINES:
        pts = curve(keys, fam, field)
        if pts:
            L.append(f"\\addplot[{col}, mark=none, line width={wd}] coordinates {{{coords(pts)}}};")
    rp = [k for k in keys if k["key"] == "reprobe_rep"]
    if rp:
        v = rp[0][field]["all"] if isinstance(rp[0][field], dict) else rp[0][field]
        L.append(f"\\addplot[rpcol, only marks, mark=*, mark size=1.6pt] coordinates {{(100,{v:.3f})}};")
        if labels:
            L.append(f"\\node[font=\\scriptsize, text=rpcol, anchor=east, inner sep=2pt] at (axis cs:98,{v:.3f}) {{ReProbe}};")
    if labels:
        for i, (fam, col, _, lab) in enumerate(LINES):
            L.append(f"\\node[font=\\scriptsize, text={col}, anchor=west, inner sep=1pt] at "
                     f"(rel axis cs:0.03,{0.92 - 0.11 * i:.2f}) {{{lab}}};")
    L += ["\\end{axis}", "\\end{tikzpicture}"]
    return "\n".join(L)


def depth_fig(sig: dict) -> str:
    keys = sig["keys"]
    a = depth_axis(keys, "ap", "Test PR-AUC", 0.2, 0.7, "0.56\\linewidth", True)
    b = depth_axis(keys, "axis_auroc", "AUROC, class-mean axis", 0.5, 0.95, "0.56\\linewidth", False)
    return "% generated by scripts/instep_v1/fig_signal.py\n" + a + "\\hfill\n" + b + "\n"


def load_points(path: Path, per_class: int, seed: int = 0) -> list[tuple]:
    rows = list(csv.DictReader(open(path)))
    rng = np.random.default_rng(seed)
    out = []
    for s in sorted({r["set"] for r in rows}):
        for c in ("0", "1"):
            rs = [r for r in rows if r["set"] == s and r["y"] == c]
            if len(rs) > per_class:
                rs = [rs[i] for i in sorted(rng.choice(len(rs), per_class, replace=False))]
            out += [(int(r["y"]), float(r["x"]), float(r["y2"])) for r in rs]
    return out


def view_fig(sig: dict, signal_dir: Path, per_class: int) -> str:
    by = {k["key"]: k for k in sig["keys"]}
    L = ["% generated by scripts/instep_v1/fig_signal.py"]
    for i, (key, title, col) in enumerate(PANELS):
        p = signal_dir / f"points_{key}.csv"
        if key not in by or not p.exists():
            continue
        pts = load_points(p, per_class)
        xy = np.array([(x, y) for _, x, y in pts])
        xy = (xy - xy.mean(0)) / (xy.std(0) + 1e-9)
        xy = np.clip(xy, -4, 4)
        L += ["\\begin{tikzpicture}",
              "\\begin{axis}[" + HEAD.format(w="0.54\\linewidth", h="3.3cm") + ",",
              f"  title={{{title}}}, xmin=-4, xmax=4, ymin=-4, ymax=4, xtick=\\empty, ytick=\\empty,",
              "  xlabel={probe direction}" + (", ylabel={orthogonal PC}" if i % 2 == 0 else "") + "]"]
        for cls, c, op in ((0, "black!30", 0.35), (1, col, 0.55)):
            sel = " ".join(f"({x:.2f},{y:.2f})" for (yy, _, _), (x, y) in zip(pts, xy) if yy == cls)
            L.append(f"\\addplot[only marks, mark=*, mark size=0.35pt, color={c}, opacity={op}] coordinates {{{sel}}};")
        ap = by[key]["ap"]["all"]
        L.append(f"\\node[font=\\scriptsize, anchor=north east, inner sep=2pt] at (rel axis cs:1,1) {{{ap:.3f}}};")
        L += ["\\end{axis}", "\\end{tikzpicture}" + ("\\hfill" if i % 2 == 0 else "\\\\[2pt]")]
    return "\n".join(L) + "\n"


def summary_md(sig: dict) -> str:
    L = ["| key | depth | test PR-AUC (ID / OOD / all) | AUROC | axis AUROC | axis var share | best PC (AUROC) | in-set ceiling |",
         "|---|---|---|---|---|---|---|---|"]
    for k in sig["keys"]:
        c = k.get("ceiling_ap", {}).get("all") if k.get("ceiling_ap") else None
        L.append(f"| {k['key']} | {k['depth']:.2f} | {k['ap']['id']:.3f} / {k['ap']['ood']:.3f} / {k['ap']['all']:.3f} | "
                 f"{k['auroc']['all']:.3f} | {k['axis_auroc']['all']:.3f} | {k['axis_var_share']:.4f} | "
                 f"{k['best_pc']} ({k['best_pc_auroc']:.3f}) | {'' if c is None else f'{c:.3f}'} |")
    return "\n".join(L) + "\n"


def main() -> None:
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--signal", type=Path, required=True, help="dir with signal_geometry.json and points_*.csv")
    p.add_argument("--out", type=Path, required=True)
    p.add_argument("--per_class", type=int, default=150)
    a = p.parse_args()
    sig = json.loads((a.signal / "signal_geometry.json").read_text())
    a.out.mkdir(parents=True, exist_ok=True)
    (a.out / "signal_depth.tex").write_text(depth_fig(sig))
    (a.out / "signal_view.tex").write_text(view_fig(sig, a.signal, a.per_class))
    (a.signal / "summary.md").write_text(summary_md(sig))
    print(summary_md(sig))


if __name__ == "__main__":
    main()
